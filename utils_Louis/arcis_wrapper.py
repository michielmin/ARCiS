def format_value(value):
    if isinstance(value, bool):
        return ".true." if value else ".false."
    if isinstance(value, float):
        return f"{value:.12g}".replace("e", "d")
    if isinstance(value, str):
        if value.startswith(("'", '"')):
            return value
        return f"'{value}'"
    return str(value)




