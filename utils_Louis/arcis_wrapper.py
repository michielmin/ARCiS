    def get_Teq(self, output_path = None, bond_albedo = None):
         ''' This function determines the equilibrium temperature of the planet based on the Arcis output (assuming an Albedo of zero for now)'''
         if output_path is None:
            print('No output path specified, using the default output path')
            output_path = self.output_path
        
         sigma = 5.670374419e-8  # W m^-2 K^-4

         if bond_albedo is None:
             log_file = Path(output_path + '/log.dat')
             text = log_file.read_text()
             matches = re.findall(r"Day-side albedo:\s*([0-9.eE+-]+)", text)
             if not matches:
                raise ValueError(f"No albedo found in {log_file}")
             bond_albedo = float(matches[-1])  # final value, if several iterations exist
             print(f"Bond albedo: {bond_albedo}")


         data = np.loadtxt(output_path +  '/irradiation')
         wavelength_um = data[:, 0]
         irradiance = data[:, 1]  # W m^-2 micron^-1

         order = np.argsort(wavelength_um)
         f_inc = np.trapz(irradiance[order], wavelength_um[order])
         print(f"Incident flux: {f_inc} W/m^2") #tot flux at the stellar surface is 55299108.536605276 W m^-2 (to convert to cgs units, multiply by 1e3)
         print(55299108.536605276 * (0.00465047 / 1)**2)

         teq = ((1.0 - bond_albedo) * f_inc / (4.0 * sigma))**0.25
         teq2 = 5777 * np.sqrt(0.00465047/ (2 * 1)) * (1 - bond_albedo)**0.25

         return teq, teq2


    def define_radius(self, Mp, logg):
        ''' This function defines the radius of the planet based on the mass (given in Jupiter masses) and logg (given in log10(g) in cgs). It returns the radius in Jupiter radii'''
        g = 10**logg
        Mjup = 1.89816e30 # g
        Rjup = 7.1492e9 # cm
        G = 6.67430e-8 # cm^3 g^-1 s
        R = np.sqrt(G * Mp * Mjup / g) / Rjup
        return R


    def check_convergence(self, output_path = None, iterations = None):
        ''' This function checks if the Arcis run has converged based on the log.dat file. It returns True if the run has converged and False if it has not.'''
        if output_path is None:
            output_path = self.output_path
        log_file = Path(output_path + '/log.dat')
        text = log_file.read_text()
        matches = re.findall(r"Converged:\s*(True|False)", text)
        if not matches:
            raise ValueError(f"No convergence information found in {log_file}")
        converged = matches[-1] == "True"  # final value, if several iterations exist
        return converged



    def tp_sanity(self, output_path = None, plot = False):
        ''' This function checks if the temperature profile is reasonable '''
        #we need to check wether there are no temperature inversions anymore below the radiative convective boundary. We can do this by checking if the temperature is monotonically decreasing with pressure below the RCB. If it is not, we can print a warning message and plot the temperature profile.
        if output_path is None:
            output_path = self.output_path

        tp = np.loadtxt(output_path + 'mixingratios.dat', skiprows = 1)
        conv =  pd.read_csv(output_path +  "convection.dat", sep=r"\s+", names=["T", "P_bar", "T_ad_ref"], na_values=["NaN"])
        mask = conv["T"].notna()

        #check if the temperature is monotonically decreasing with pressure below the RCB
        if not np.all(np.diff(tp[mask, 0]) <= 0):
            print(f"Warning: The temperature profile is not monotonically decreasing with pressure below the RCB in {output_path}. This could indicate a problem with the model.")
            if plot:
                plt.plot(tp[:, 0], tp[:, 1], color = 'black', ls = '-')
                plt.scatter(tp[mask, 0], tp[mask, 1], color='red', alpha=0.3)
                plt.yscale('log')
                plt.xlabel('Temperature (K)')
                plt.ylabel('Pressure (bar)')
                plt.gca().invert_yaxis()
                plt.title('File: ' + output_path)
                plt.show()


        




