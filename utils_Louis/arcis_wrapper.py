    def set(self, key, value):
        ''' This function allows you to set flags in the Arcis input file. It will search for the flag and relace the vlue. If it does not find the flag it will add it to the end of the file'''
        value = format_value(value)

        for i, line in enumerate(self.input_lines):
            body, *comment = line.split("!", 1)

            if "=" not in body:
                continue

            lhs, rhs = body.split("=", 1)

            if lhs.strip().lower() == key.lower():
                new_line = f"{lhs.strip()}={value}"

                if comment:
                    new_line += " !" + comment[0]

                self.input_lines[i] = new_line
                return self

        # If key was not found, append it
        self.input_lines.append(f"{key}={value}")
        return self


    def write_input(self):
        text = "\n".join(self.input_lines) + "\n"

        Path(self.input_file).write_text(text)
        return self.input_file




